package com.fibonanci.app.domain

import androidx.compose.ui.graphics.Color
import com.fibonanci.app.ui.theme.AppColors
import java.util.Locale

// health tier representing general financial vitality
enum class HealthTier {
    excellent, // 85 - 100 (prima)
    good, // 70 - 84 (stabil)
    caution, // 50 - 69 (waspada)
    deficit, // < 50 (kritis)
}

// single financial health pillar metric breakdown
data class HealthPillarMetric(
    val title: String,
    val description: String,
    val score: Double, // 0..100
    val displayValue: String,
    val benchmark: String,
    val isHealthy: Boolean,
)

// complete diagnostic report generated by FinancialHealthService
data class FinancialHealthReport(
    val overallScore: Int, // 0..100
    val tier: HealthTier,
    val emergencyRunway: HealthPillarMetric,
    val fixedCommitment: HealthPillarMetric,
    val savingsMargin: HealthPillarMetric,
    val spendPacing: HealthPillarMetric,
    val recommendations: List<String>,
    val totalLiquidAssets: Double,
    val totalPocketsAmount: Double,
) {
    val tierColor: Color
        get() = when (tier) {
            HealthTier.excellent -> AppColors.neoMint
            HealthTier.good -> AppColors.neoChartreuse
            HealthTier.caution -> Color(0xFFFFA439)
            HealthTier.deficit -> AppColors.statusDeficit
        }

    val tierLabel: String
        get() = when (tier) {
            HealthTier.excellent -> "Prima"
            HealthTier.good -> "Stabil"
            HealthTier.caution -> "Waspada"
            HealthTier.deficit -> "Kritis"
        }

    val tierHeadline: String
        get() = when (tier) {
            HealthTier.excellent -> "Keuanganmu Berada di Kondisi Prima!"
            HealthTier.good -> "Keuangan Stabil, Siap Ditingkatkan."
            HealthTier.caution -> "Perlu Penyesuaian Pengeluaran."
            HealthTier.deficit -> "Arus Kas Memerlukan Evaluasi Segera."
        }
}

// dart toStringAsFixed
internal fun Double.toFixed(digits: Int): String = String.format(Locale.US, "%.${digits}f", this)

// dart double.round(): half away from zero
internal fun Double.dartRound(): Long = if (this < 0) -Math.round(-this) else Math.round(this)
